"""Trace sample gold answers back to the evidence (spec 0002, part 2).

Run:    python code/trace_gold.py
Writes: code/docs/GOLD_TRACE.md

For each sample case:
  * resolves identifiers (current + audit history) as of audit_at
  * for every gold step, lists every evidence file mentioning the resource_id,
    its captured_at, whether it is <= audit_at, nearby record_type/status
    fields, and which file the gold cites
  * compares resources found via identifier search against the gold resource set
Standard library only; `pip install pypdf` to include PDF text.
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
from collections import defaultdict
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in [HERE, *HERE.parents] if (p / "dataset").is_dir())
DS = ROOT / "dataset"
OUT = ROOT / "code" / "docs" / "GOLD_TRACE.md"

RES_RE = re.compile(
    r"\b(?:account|search|support|analytics|cache|export|data_flow|backup|legal_hold|"
    r"tombstone|audit_record|email_delivery|object|marketing)_\d+\b"
)
FIELD_RE = re.compile(
    r"(record_type|status_code|status|state|enabled|restore_allowed|account_status|result|"
    r"event|retention_until|hold)[\"']?\s*[:=]\s*[\"']?([A-Za-z0-9_\-:.]+)",
    re.I,
)


def ts(s: str) -> datetime:
    return datetime.fromisoformat(s.strip().replace("Z", "+00:00"))


def read_csv(name: str) -> list[dict]:
    with (DS / name).open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


samples = read_csv("sample_deletion_requests.csv")
gold = {g["case_id"]: json.loads(g["steps_json"]) for g in read_csv("sample_output.csv")}
gold_status = {g["case_id"]: g["deletion_status"] for g in read_csv("sample_output.csv")}
identities = read_csv("user_identities.csv")
audit = read_csv("user_audit_log.csv")
activity = read_csv("system_activity.csv")
manifest = read_csv("evidence_files.csv")

# ---------- load evidence text ----------
try:
    from pypdf import PdfReader  # type: ignore
except ImportError:
    PdfReader = None


def resolve(fp: str) -> Path | None:
    for base in (DS, DS / "evidence", ROOT):
        if (base / fp).exists():
            return base / fp
    return None


texts: dict[str, str] = {}
captured: dict[str, datetime] = {}
origin: dict[str, str] = {}
for r in manifest:
    path = resolve(r["file_path"])
    captured[r["file_id"]] = ts(r["captured_at"])
    origin[r["file_id"]] = r["origin"]
    if path is None:
        continue
    ext = path.suffix.lower()
    if ext == ".pdf" and PdfReader:
        texts[r["file_id"]] = "\n".join((pg.extract_text() or "") for pg in PdfReader(str(path)).pages)
    elif ext not in (".png", ".jpg", ".jpeg", ".webp", ".gif", ".pdf"):
        texts[r["file_id"]] = path.read_text(encoding="utf-8", errors="replace")


def mentions(fid: str, needle: str, window: int = 220) -> list[str]:
    """Return context windows around whole-token matches of needle."""
    text = texts.get(fid, "")
    out = []
    for m in re.finditer(r"(?<![\w.@])" + re.escape(needle) + r"(?![\w@])", text):
        out.append(text[max(0, m.start() - window // 2): m.end() + window // 2].replace("\n", " ⏎ "))
        if len(out) >= 3:
            break
    return out


# ---------- identity ----------
def identifiers(email: str, audit_at: datetime) -> tuple[str | None, set[str]]:
    email_l = email.strip().lower()
    uid = next((r["user_id"] for r in identities if r["email"].strip().lower() == email_l), None)
    if uid is None:
        uid = next(
            (r["user_id"] for r in audit if r["field_name"] == "email"
             and email_l in (r["old_value"].strip().lower(), r["new_value"].strip().lower())),
            None,
        )
    ids = {email, hashlib.sha256(email.encode()).hexdigest()}
    if uid:
        ids.add(uid)
        cur = next(r for r in identities if r["user_id"] == uid)
        ids |= {cur["email"], cur["phone"], cur["email_hash"], cur["name"]}
        for r in audit:
            if r["user_id"] == uid and ts(r["event_time"]) <= audit_at:
                ids |= {v for v in (r["old_value"], r["new_value"]) if v}
        for e in [i for i in ids if "@" in i]:
            ids.add(hashlib.sha256(e.encode()).hexdigest())
    return uid, {i for i in ids if i}


lines: list[str] = ["# Gold trace (generated by code/trace_gold.py)\n"]
summary = []

for s in samples:
    cid = s["case_id"]
    audit_at = ts(s["audit_at"])
    uid, ids = identifiers(s["email"], audit_at)
    steps = gold[cid]
    gold_res = {(st["system_id"], st["resource_id"]) for st in steps}

    # discovery: resources co-mentioned with any identifier (strong ids only, not names)
    strong = {i for i in ids if "@" in i or len(i) == 64 or i.startswith("user_") or re.fullmatch(r"\+?[\d\s\-()]{7,}", i)}
    found: dict[str, set[str]] = defaultdict(set)
    for fid, text in texts.items():
        if captured[fid] > audit_at:
            continue
        for ln in re.split(r"\n|(?<=\})\s*,\s*(?=\{)", text):
            if any(i in ln for i in strong):
                for rid in RES_RE.findall(ln):
                    found[rid].add(fid)
    for a in activity:
        if a["event_type"] == "LINK_RESOURCE_IDENTITY" and ts(a["event_time"]) <= audit_at and any(i in a["details"] for i in strong):
            found[a["resource_id"]].add(a["activity_id"])

    gold_ids = {r for _, r in gold_res}
    hit, miss, extra = gold_ids & set(found), gold_ids - set(found), set(found) - gold_ids
    summary.append((cid, gold_status[cid], len(gold_ids), len(hit), sorted(miss), sorted(extra)[:6]))

    lines.append(f"\n## {cid} — gold {gold_status[cid]} (reported {s['reported_status']})")
    lines.append(f"- email `{s['email']}` → user `{uid}`; audit_at {s['audit_at']}")
    lines.append(f"- identifiers: {sorted(i for i in ids if len(i) < 64)} + {sum(len(i) == 64 for i in ids)} hashes")
    lines.append(f"- discovery: gold resources {len(gold_ids)}, found {len(hit)}, missed {sorted(miss)}, extra {sorted(extra)}\n")

    for st in steps:
        rid, ev = st["resource_id"], st["evidence_id"]
        lines.append(f"### step {st['step_no']} {st['operation']} {st['system_id']}/{rid} cite=`{ev or '—'}`")
        for fid in sorted(texts, key=lambda f: captured[f]):
            ctx = mentions(fid, rid)
            if not ctx:
                continue
            ok = "≤audit" if captured[fid] <= audit_at else "AFTER"
            mark = " **◀ GOLD**" if fid == ev else ""
            fields = sorted({f"{k}={v}" for c in ctx for k, v in FIELD_RE.findall(c)})
            lines.append(f"- `{fid}` {captured[fid]:%Y-%m-%d %H:%M} {ok} [{origin[fid]}]{mark} fields={fields[:8]}")
            lines.append(f"  - `{ctx[0][:260]}`")
        if ev and ev not in texts:
            lines.append(f"- cited `{ev}` is an image/PDF without text: [{origin.get(ev)}] {captured.get(ev)}")
        lines.append("")

# ---------- summary ----------
head = ["\n# Summary: discovery recall per case\n",
        "| case | gold | gold res | found | missed | extra (first 6) |", "|---|---|---|---|---|---|"]
head += [f"| {c} | {g} | {n} | {h} | {m} | {e} |" for c, g, n, h, m, e in summary]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines[:1] + head + lines[1:]) + "\n", encoding="utf-8")
print(f"Wrote {OUT.relative_to(ROOT)}")